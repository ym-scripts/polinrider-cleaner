const color = process.stdout.isTTY && !process.env.NO_COLOR;
const paint = (code) => (s) => (color ? `\x1b[${code}m${s}\x1b[0m` : s);
const [red, green, yellow, dim] = [31, 32, 33, 2].map(paint);
const STATUS_COLOR = { CLEANED: green, RESTORED: green, 'PR-OPENED': green, 'WOULD-CLEAN': yellow, 'WOULD-RESTORE': yellow, OVERWRITTEN: yellow, 'SKIPPED-ARCHIVED': dim };

function log(r) {
  const tag = (STATUS_COLOR[r.status] || red)(`[${r.status.padEnd(16)}]`);
  console.log(`${tag} ${r.repo}@${r.branch}  ${dim((r.notes || []).join(' | '))}`);
}

function parseArgs(argv) {
  const o = { apply: false, viaPr: false, restoreOverwritten: false, repo: [], owner: [], branch: null, includeForks: false, jobs: 6, out: null, yes: false };
  const need = (i, flag) => {
    if (argv[i + 1] === undefined || argv[i + 1].startsWith('-')) usage(`${flag} needs a value`);
    return argv[i + 1];
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    switch (a) {
      case '--apply': o.apply = true; break;
      case '--dry-run': o.apply = false; break;
      case '--via-pr': o.viaPr = true; break;
      case '--restore-overwritten': o.restoreOverwritten = true; break;
      case '-r': case '--repo': o.repo.push(need(i, a)); i++; break;
      case '-o': case '--owner': o.owner.push(need(i, a)); i++; break;
      case '-b': case '--branch': o.branch = need(i, a); i++; break;
      case '--include-forks': o.includeForks = true; break;
      case '-j': case '--jobs': o.jobs = Number(need(i, a)); i++; if (!(o.jobs >= 1)) usage('--jobs must be a positive number'); break;
      case '--out': o.out = need(i, a); i++; break;
      case '-y': case '--yes': o.yes = true; break;
      case '-v': case '--version': console.log(VERSION); process.exit(0);
      case '-h': case '--help': console.log(HELP); process.exit(0);
      default: usage(`unknown option: ${a}`);
    }
  }
  if (o.viaPr && !o.apply) usage('--via-pr only makes sense with --apply');
  return o;
}

function usage(msg) {
  console.error(`polinrider-cleaner: ${msg}\nRun with --help for usage.`);
  process.exit(2);
}

async function main() {
  const o = parseArgs(process.argv.slice(2));
  for (const [cmd, args, hint] of [['git', ['--version'], 'install git'], ['gh', ['auth', 'status'], 'install the GitHub CLI and run: gh auth login']]) {
    const r = await run(cmd, args, { check: false }).catch(() => ({ code: -1 }));
    if (r.code !== 0) { console.error(red(`✖ ${cmd} is not ready: ${hint}`)); process.exit(2); }
  }

  const outDir = resolve(o.out || `polinrider-report-${new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)}`);
  mkdirSync(outDir, { recursive: true });
  o.work = mkdtempSync(join(tmpdir(), 'polinrider-'));
  HOOKS = join(o.work, 'no-hooks');
  mkdirSync(HOOKS);

  let code = 2;
  try {
    const repos = await listRepos(o);
    console.log(`polinrider-cleaner  ${repos.length} repos  ${o.apply ? red('APPLY') : green('DRY RUN')}  ${dim(`report: ${outDir}`)}\n`);
    if (o.apply && !o.yes) {
      const rl = createInterface({ input: process.stdin, output: process.stdout });
      const what = o.viaPr ? 'open PRs with' : 'commit and push';
      const answer = await rl.question(`This will ${what} fixes on infected branches${o.restoreOverwritten ? ' and restore overwritten branches' : ''}. Type "yes": `);
      rl.close();
      if (answer.trim() !== 'yes') { console.log('Aborted.'); return; }
    }

    const results = (await pool(repos, o.jobs, (r) => processRepo(r, o, outDir))).flat();
    writeFileSync(join(outDir, 'report.json'), JSON.stringify(results, null, 2));
    const counts = {};
    for (const r of results) counts[r.status] = (counts[r.status] || 0) + 1;
    const summary = Object.entries(counts).sort().map(([k, v]) => `${k}=${v}`).join(', ');
    console.log(`\n${summary ? `Summary: ${summary}` : green('✔ No infections found.')}`);
    console.log(dim(`Patches and report.json are in ${outDir}. Review the .patch files before running with --apply.`));
    if (counts.MANUAL) console.log(yellow('▲ MANUAL entries were not touched; inspect them by hand.'));
    const done = new Set(['CLEANED', 'RESTORED', 'PR-OPENED', 'SKIPPED-ARCHIVED']);
    code = results.every((r) => done.has(r.status)) ? 0 : 1;
  } finally {
    rmSync(o.work, { recursive: true, force: true });
    process.exitCode = code;
  }
}

// Run as a CLI, but not when imported by the tests.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main();
