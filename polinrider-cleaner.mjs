/**
 * Layer 1: undo the attacker's amend using the `before` SHA that GitHub's activity log keeps
 * for every force-push. Returns { overwritten } when the branch was replaced instead of amended.
 */
async function reverseForcePushes(dir, full, branch, notes) {
  let acts;
  try {
    acts = await ghApi(`repos/${full}/activity?ref=${encodeURIComponent(`refs/heads/${branch}`)}&activity_type=force_push&per_page=100`) || [];
  } catch (e) {
    notes.push(`activity log unavailable: ${e.message}`);
    return {};
  }
  const parents = async (sha) => (await ghApi(`repos/${full}/commits/${sha}`)).parents.map((p) => p.sha).join(',');
  for (const a of acts) { // newest first
    const { before, after } = a;
    if (!before || !after || /^0+$/.test(before)) continue;
    let cmp;
    try { cmp = await ghApi(`repos/${full}/compare/${after}...${branch.split('/').map(encodeURIComponent).join('/')}`); } catch { continue; }
    if (!['identical', 'ahead'].includes(cmp?.status)) continue; // attacker's commit no longer in the branch
    if ((await git(dir, ['fetch', '-q', '--depth=1', 'origin', before, after], { check: false })).code !== 0) {
      notes.push(`force-push ${a.timestamp}: original commit ${before.slice(0, 8)} can no longer be fetched`);
      continue;
    }
    const sigAfter = new Set((await scanTree(dir, after)).map(([p]) => p));
    const sigBefore = new Set((await scanTree(dir, before)).map(([p]) => p));
    if (![...sigAfter].some((p) => !sigBefore.has(p))) continue; // this force-push didn't add the infection
    if (await parents(after) !== await parents(before)) {
      notes.push(`branch OVERWRITTEN by force-push ${a.timestamp}: original tip was ${before.slice(0, 8)}`);
      return { overwritten: { before, after, beforeInfected: sigBefore.size > 0 } };
    }
    // the amend can also carry the owner's own unpushed work; only trust the reverse diff
    // when every file it touches is a known infection file
    const touched = (await git(dir, ['diff', '--name-only', '-z', after, before])).stdout.split('\0').filter(Boolean);
    if (touched.some((p) => !isKitPath(p, sigAfter))) {
      notes.push(`force-push ${a.timestamp} also changed non-malware files; using signature cleanup instead`);
      continue;
    }
    const patch = (await git(dir, ['diff', '--binary', after, before])).buf;
    if (!patch.length) continue;
    if ((await git(dir, ['apply', '--3way', '--index', '-'], { input: patch, check: false })).code === 0) {
      notes.push(`reverted force-push ${a.timestamp} (${after.slice(0, 8)} -> original ${before.slice(0, 8)})`);
    } else {
      await git(dir, ['reset', '-q', '--hard', 'HEAD']);
      notes.push(`could not cleanly reverse force-push ${a.timestamp}; using signature cleanup`);
    }
  }
  return {};
}

/** Layer 2: signature-based fixes on the working tree. */
export async function surgicalClean(dir, notes) {
  const files = (await git(dir, ['ls-files', '-z'])).stdout.split('\0').filter(Boolean);
  const removed = [], changed = new Set();
  const abs = (rel) => join(dir, rel);
  const read = (rel) => (existsSync(abs(rel)) ? readFileSync(abs(rel)) : null);
  const rm = async (rel) => { await git(dir, ['rm', '-q', '-f', '--', rel]); removed.push(rel); };
  const write = async (rel, text) => { writeFileSync(abs(rel), text); await git(dir, ['add', '--', rel]); changed.add(rel); };

  for (const rel of files) {
    const buf = read(rel);
    if (!buf) continue;
    if (isFakeFont(rel, buf)) { await rm(rel); continue; }
    const text = decode(buf);
    if (text === null) continue;
    const name = basename(rel);
    const stripped = stripPayload(text);
    if (stripped === '') { await rm(rel); continue; } // the whole file was payload (api.js)
    let next = stripped ?? text;
    if (name === '.gitignore') next = cleanGitignore(next) ?? next;
    if (name === 'package.json') next = cleanPackageJson(next) ?? next;
    if (next !== text) await write(rel, next);
  }

  for (const rel of files) {
    const buf = read(rel);
    if (!buf) continue;
    const text = decode(buf) ?? '';
    if (isMaliciousVscode(rel, text)
      || (rel.endsWith('.vscode/launch.json') && text.includes('flo-ct-flo360'))
      || (rel.endsWith('.vscode/spellright.dict') && text.split(/\s+/).filter(Boolean).join(' ') === 'Contentful Lerna')
      || (rel.endsWith('.vscode/extensions.json') && text.includes('myml.vscode-markdown-plantuml-preview') && text.includes('jebbs.plantuml') && (text.match(/"/g) || []).length <= 8)) {
      await rm(rel);
    } else if (rel.endsWith('fonts/README.md') && text.includes('Blockchain Explorer')) {
      await rm(rel);
      const fontDir = rel.slice(0, -'README.md'.length);
      for (const name of KIT_FONT_FILES) {
        const fp = fontDir + name;
        if (!files.includes(fp) || !existsSync(abs(fp))) continue;
        const refs = await git(dir, ['grep', '-l', '-F', name.replace(/\.[^.]+$/, ''), '--', '.', `:!${fontDir}`], { check: false });
        if (refs.stdout.trim()) notes.push(`kept ${fp}: referenced elsewhere`);
        else await rm(fp);
      }
    }
  }
  if (removed.length) notes.push(`removed: ${removed.join(', ')}`);
  if (changed.size) notes.push(`cleaned: ${[...changed].sort().join(', ')}`);
}

// ---------- per repo ----------

async function processRepo(repo, o, outDir) {
  const full = repo.full_name;
  const results = [];
  if (repo.archived) return [{ repo: full, branch: '*', status: 'SKIPPED-ARCHIVED', notes: ['unarchive to scan and clean'] }];
  if (repo.size === 0) return results;
  const tmp = mkdtempSync(join(o.work, 'repo-'));
  try {
    let c;
    for (let attempt = 1; attempt <= 3; attempt++) {
      rmSync(tmp, { recursive: true, force: true });
      c = await git(undefined, ['clone', '-q', '--no-checkout', '--depth=1', '--no-single-branch', `https://github.com/${full}.git`, tmp], { check: false });
      if (c.code === 0 || /not found/i.test(c.stderr)) break;
      await sleep(5000 * attempt);
    }
    if (c.code !== 0) return [{ repo: full, branch: '*', status: 'ERROR', notes: [c.stderr.trim().slice(-300)] }];
    let branches = (await git(tmp, ['for-each-ref', '--format=%(refname)', 'refs/remotes/origin'])).stdout.split('\n')
      .map((r) => r.replace('refs/remotes/origin/', '')).filter((b) => b && b !== 'HEAD');
    if (o.branch) branches = branches.filter((b) => b === o.branch);

    for (const br of branches) {
      const ref = `refs/remotes/origin/${br}`;
      const signatures = await scanTree(tmp, ref);
      if (!signatures.length) continue;
      const res = { repo: full, branch: br, status: 'ERROR', signatures, notes: [] };
      results.push(res);
      try {
        await git(tmp, ['checkout', '-q', '-f', '-B', 'clean-work', ref]);
        await git(tmp, ['clean', '-qfdx']);
        const { overwritten } = await reverseForcePushes(tmp, full, br, res.notes);
        if (overwritten) { await restoreOverwritten(tmp, repo, br, ref, overwritten, o, res); continue; }
        await surgicalClean(tmp, res.notes);

        // Layer 3: re-scan exactly what would be committed
        const tree = (await git(tmp, ['write-tree'])).stdout.trim();
        const remaining = await scanTree(tmp, tree);
        const diff = (await git(tmp, ['diff', '--cached', '--binary'])).buf;
        const file = join(outDir, `${`${full}__${br}`.replace(/[^\w.-]+/g, '_')}.patch`);
        writeFileSync(file, diff);
        res.patch = file;
        if (remaining.length) {
          res.status = 'MANUAL';
          res.notes.push(`still infected after cleaning: ${remaining.map(([p, r]) => `${p} (${r})`).join(', ')}`);
        } else if (!diff.length) {
          res.status = 'MANUAL';
          res.notes.push('signatures found but nothing to change');
        } else if (!o.apply) {
          res.status = 'WOULD-CLEAN';
        } else if (!repo.permissions?.push) {
          res.status = 'NO-PUSH-ACCESS';
        } else {
          await git(tmp, ['commit', '-q', '--no-verify', '-m', COMMIT_MSG]);
          await pushFix(tmp, full, br, o, res);
        }
      } catch (e) {
        res.notes.push(e.message.slice(-400));
      }
    }
  } catch (e) {
    results.push({ repo: full, branch: '*', status: 'ERROR', notes: [e.message.slice(-400)] });
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  for (const r of results) log(r);
  return results;
}

async function restoreOverwritten(tmp, repo, br, ref, { before, after, beforeInfected }, o, res) {
  const tip = (await git(tmp, ['rev-parse', ref])).stdout.trim();
  if (tip !== after) {
    res.status = 'MANUAL';
    res.notes.push(`new commits were added on top of the attacker's ${after.slice(0, 8)}; restore by hand`);
  } else if (beforeInfected) {
    res.status = 'MANUAL';
    res.notes.push(`original tip ${before.slice(0, 8)} is itself infected (earlier wave); restore it, then run again`);
  } else if (!o.restoreOverwritten) {
    res.status = 'OVERWRITTEN';
    res.notes.push(`run with --restore-overwritten to put ${br} back on ${before.slice(0, 8)}`);
  } else if (!o.apply) {
    res.status = 'WOULD-RESTORE';
  } else if (!repo.permissions?.push) {
    res.status = 'NO-PUSH-ACCESS';
  } else {
    // the lease makes this a no-op unless the branch still points at the attacker's commit
    const p = await git(tmp, ['push', `--force-with-lease=refs/heads/${br}:${after}`, 'origin', `${before}:refs/heads/${br}`], { check: false });
    res.status = p.code === 0 ? 'RESTORED' : 'PUSH-FAILED';
    if (p.code) res.notes.push(p.stderr.trim().slice(-300));
  }
}

async function pushFix(tmp, full, br, o, res) {
  if (!o.viaPr) {
    const p = await git(tmp, ['push', '-q', 'origin', `HEAD:refs/heads/${br}`], { check: false }); // never --force
    res.status = p.code === 0 ? 'CLEANED' : 'PUSH-FAILED';
    if (p.code) res.notes.push(p.stderr.trim().slice(-300));
    return;
  }
  const head = `security/remove-polinrider-${br.replace(/[^A-Za-z0-9._-]/g, '-')}`;
  let p = await git(tmp, ['push', '-q', 'origin', `HEAD:refs/heads/${head}`], { check: false });
  if (p.code === 0) {
    p = await run('gh', ['pr', 'create', '-R', full, '-B', br, '-H', head,
      '-t', 'security: remove PolinRider malware injection', '-b', COMMIT_MSG], { check: false });
  }
  res.status = p.code === 0 ? 'PR-OPENED' : 'PUSH-FAILED';
  res.notes.push((p.stdout || p.stderr).trim().slice(-300));
}

async function listRepos(o) {
  if (o.repo.length) return Promise.all(o.repo.map((r) => ghApi(`repos/${r}`)));
  const repos = await ghApi('user/repos?affiliation=owner,collaborator,organization_member&per_page=100', { paginate: true });
  const seen = new Set(repos.map((r) => r.full_name));
  for (const org of await ghApi('user/orgs?per_page=100', { paginate: true })) {
    for (const r of await ghApi(`orgs/${org.login}/repos?per_page=100`, { paginate: true })) {
      if (!seen.has(r.full_name)) { seen.add(r.full_name); repos.push(r); }
    }
  }
  const owners = new Set(o.owner.map((x) => x.toLowerCase()));
  return repos.filter((r) => (!owners.size || owners.has(r.owner.login.toLowerCase())) && (o.includeForks || !r.fork));
}

async function pool(items, n, fn) {
  const out = [];
  let i = 0;
  await Promise.all(Array.from({ length: Math.min(n, items.length) }, async () => {
    while (i < items.length) { const k = i++; out[k] = await fn(items[k]); }
  }));
  return out;
}

