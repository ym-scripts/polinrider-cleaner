// ---------- signatures ----------

export const GITIGNORE_MARKERS = new Set(['branch_structure.json', 'temp_auto_push.bat', 'temp_interactive_push.bat']);
// 200+ blanks followed by 200+ characters of code on the same line: the hidden-payload trick
export const PAYLOAD_RE = /[ \t]{200,}(?=\S.{199,})/;
const PAYLOAD_GREP = '[[:blank:]]{200,}[^[:blank:]]';
const CREATE_REQUIRE_RE = /^import \{ ?createRequire ?\} from ['"](?:node:)?module['"];?[ \t]*\r?\n(?:[ \t]*\r?\n)?const require = createRequire\(import\.meta\.url\);?[ \t]*\r?\n(?:[ \t]*\r?\n)?/gm;
const PKG_SCRIPT_SRC = String.raw`node\s+(?:\.\/)?api\.js\s*&&\s*`;
const PKG_ONLY_RE = /"\s*node\s+(?:\.\/)?api\.js\s*"/;
const FAKE_FONT_RE = /(^|\/)fonts\/[^/]+\.(woff2?|ttf|eot|otf|lfk)$/i;
export const KIT_FONT_FILES = ['brands-400', 'regular-400', 'solid-900'].flatMap((w) =>
  ['eot', 'svg', 'ttf', 'woff', 'woff2'].map((ext) => `fa-${w}.${ext}`));
const KIT_VSCODE = ['tasks.json', 'settings.json', 'launch.json', 'extensions.json', 'spellright.dict'];
const COMMIT_MSG = `security: remove PolinRider malware injection

Removes the obfuscated payload, hidden config tails, .gitignore markers and
auto-run hooks injected by a force-push. Generated by polinrider-cleaner.`;

const utf8 = new TextDecoder('utf-8', { fatal: true });
export function decode(buf) {
  if (buf.includes(0)) return null;
  try { return utf8.decode(buf); } catch { return null; }
}

/** Cut each line at its hidden payload; drop the injected createRequire shim. Returns null if untouched, '' if the whole file was payload. */
export function stripPayload(text) {
  if (!PAYLOAD_RE.test(text)) return null;
  let out = text.split('\n').map((line) => {
    const m = PAYLOAD_RE.exec(line);
    return m ? line.slice(0, m.index) : line;
  }).join('\n');
  if (!out.trim()) return '';
  const rest = out.replace(CREATE_REQUIRE_RE, '');
  if (rest !== out && !/\brequire\s*\(/.test(rest)) out = rest;
  return out.endsWith('\n') ? out : out + '\n';
}

export function cleanGitignore(text) {
  const lines = text.split('\n');
  if (!lines.some((l) => GITIGNORE_MARKERS.has(l.trim()))) return null;
  const keep = lines.filter((l) => !GITIGNORE_MARKERS.has(l.trim()) && l.trim() !== '.gitignore');
  return keep.join('\n').replace(/\n+$/, '') + '\n';
}

export function cleanPackageJson(text) {
  const re = new RegExp(PKG_SCRIPT_SRC, 'g');
  return re.test(text) ? text.replace(re, '') : null;
}

export function packageJsonInfected(text) {
  return new RegExp(PKG_SCRIPT_SRC).test(text) || PKG_ONLY_RE.test(text);
}

/** A VS Code task that silently runs node on a font, a non-JS file, or as a hidden task when the folder opens. */
export function isMaliciousVscode(path, text) {
  if (!/(^|\/)\.vscode\/(tasks|settings)\.json$/.test(path) || !text.includes('folderOpen')) return false;
  const runsNode = /"command"\s*:\s*"[^"]*\bnode\b/.test(text);
  if (runsNode && (/fonts\//.test(text) || /\.(woff2?|ttf|eot|otf|lfk|svg|png|jpe?g|gif|ico|dat|bin)\b/.test(text) || /"hide"\s*:\s*true/.test(text))) return true;
  return path.endsWith('settings.json') && /"task\.allowAutomaticTasks"\s*:\s*true/.test(text);
}

/** A "font" under fonts/ that is valid text is a disguised script (real font files are binary). */
export function isFakeFont(path, buf) {
  return FAKE_FONT_RE.test(path) && buf.length > 0 && decode(buf) !== null;
}

export function isKitPath(path, signaturePaths) {
  if (signaturePaths.has(path)) return true;
  const name = basename(path);
  if (KIT_VSCODE.some((n) => path.endsWith(`.vscode/${n}`))) return true;
  if (/(^|\/)fonts\//.test(path) && (KIT_FONT_FILES.includes(name) || name === 'README.md' || FAKE_FONT_RE.test(path))) return true;
  return name === '.gitignore';
}

// ---------- processes ----------

let HOOKS = ''; // empty dir used as core.hooksPath, so no hook ever runs

export function run(cmd, args, { cwd, input, check = true } = {}) {
  return new Promise((res, rej) => {
    const p = spawn(cmd, args, { cwd, env: { ...process.env, GIT_TERMINAL_PROMPT: '0', GH_PROMPT_DISABLED: '1' } });
    const out = [], err = [];
    p.stdout.on('data', (d) => out.push(d));
    p.stderr.on('data', (d) => err.push(d));
    p.on('error', rej);
    p.on('close', (code) => {
      const r = { code, buf: Buffer.concat(out), stdout: Buffer.concat(out).toString('utf8'), stderr: Buffer.concat(err).toString('utf8') };
      if (check && code !== 0) rej(new Error(`${cmd} ${args.join(' ')} -> ${code}\n${r.stderr.trim()}`));
      else res(r);
    });
    if (input !== undefined) p.stdin.end(input); else p.stdin.end();
  });
}

export function git(dir, args, opts) {
  const cfg = ['-c', `core.hooksPath=${HOOKS || join(tmpdir(), 'polinrider-no-hooks')}`, '-c', 'advice.detachedHead=false',
    '-c', 'core.autocrlf=false', '-c', 'core.longpaths=true', '-c', 'core.quotepath=off'];
  return run('git', [...cfg, ...args], { cwd: dir, ...opts });
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function ghApi(path, { paginate = false } = {}) {
  const args = ['api', path, ...(paginate ? ['--paginate', '--jq', '.[]'] : [])];
  let r;
  for (let attempt = 1; attempt <= 5; attempt++) {
    r = await run('gh', args, { check: false });
    if (r.code === 0) {
      const out = r.stdout.trim();
      if (paginate) return out ? out.split('\n').filter(Boolean).map((l) => JSON.parse(l)) : [];
      return out ? JSON.parse(out) : null;
    }
    const e = r.stderr.toLowerCase();
    if (e.includes('rate limit')) await sleep(30000 * attempt);
    else if (/connection reset|timeout|internet connection|eof|50[234]/.test(e)) await sleep(5000 * attempt);
    else break;
  }
  throw new Error(`gh api ${path}: ${r.stderr.trim().slice(-200)}`);
}

// ---------- detection ----------

/** Signatures present in a commit or tree: [[path, reason], ...] */
export async function scanTree(dir, ref) {
  const hits = [];
  const seen = new Set();
  const hit = (p, why) => { if (!seen.has(p)) { seen.add(p); hits.push([p, why]); } };
  const files = (await git(dir, ['ls-tree', '-r', '-z', '--name-only', ref])).stdout.split('\0').filter(Boolean);
  const show = async (p) => (await git(dir, ['show', `${ref}:${p}`], { check: false })).buf;
  const text = async (p) => decode(await show(p)) ?? '';

  for (const f of files) {
    if (basename(f) === '.gitignore' && cleanGitignore(await text(f)) !== null) hit(f, 'gitignore-markers');
  }
  const g = await git(dir, ['grep', '-I', '-l', '-z', '-E', PAYLOAD_GREP, ref, '--', '.'], { check: false });
  for (const entry of g.stdout.split('\0').filter(Boolean)) {
    const p = entry.startsWith(`${ref}:`) ? entry.slice(ref.length + 1) : entry;
    if ((await text(p)).split('\n').some((l) => PAYLOAD_RE.test(l))) hit(p, 'hidden-payload');
  }
  for (const f of files) {
    const name = basename(f);
    if (FAKE_FONT_RE.test(f) && isFakeFont(f, await show(f))) hit(f, 'fake-font-script');
    else if (name === 'package.json' && packageJsonInfected(await text(f))) hit(f, 'package-json-runs-api.js');
    else if (/(^|\/)\.vscode\/(tasks|settings)\.json$/.test(f) && isMaliciousVscode(f, await text(f))) hit(f, 'vscode-autorun');
    else if (f.endsWith('fonts/README.md') && (await text(f)).includes('Blockchain Explorer')) hit(f, 'decoy-fonts-readme');
  }
  return hits;
}

